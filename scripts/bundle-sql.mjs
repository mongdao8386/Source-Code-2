/**
 * Concatenates every migration (in filename order) plus seed.sql into
 * supabase/applyall.sql, for pasting into the Supabase SQL Editor when you
 * don't have the database password to hand.
 *
 * The output is derived and gitignored: regenerate it after any schema change
 * rather than editing it, or you will apply a stale schema.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const migrationsDir = 'supabase/migrations';
const files = readdirSync(migrationsDir).filter((f) => f.endsWith('.sql')).sort();

let out =
  '-- GENERATED by `npm run sql:bundle` — do not edit.\n' +
  '-- Paste into the Supabase SQL Editor and Run. Safe to re-run.\n';

for (const f of files) {
  out += `\n-- ===== ${f} =====\n` + readFileSync(join(migrationsDir, f), 'utf8');
}
out += '\n-- ===== seed.sql =====\n' + readFileSync('supabase/seed.sql', 'utf8');

writeFileSync('supabase/applyall.sql', out);
console.log(`wrote supabase/applyall.sql (${files.length} migration(s) + seed)`);
